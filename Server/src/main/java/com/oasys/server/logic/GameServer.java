package com.oasys.server.logic;

public class GameServer {

    /**
     * The GameServer class manages the game state, players, and game flow. It is responsible for adding players,
     * starting, pausing, resuming, and ending the game. Additionally, it provides a method for shuffling the list of players.
     *
     * Attributes:
     * - players: A list of Player objects representing the participants in the game.
     * - isGameRunning: A boolean flag indicating whether the game is currently running.
     * - isGamePaused: A boolean flag indicating whether the game is paused.
     *
     * Methods:
     * - addPlayer: Adds a new player to the game.
     * - getPlayers(): Returns the list of players currently in the game.
     * - startGame(): Starts the game by setting isGameRunning to true and isGamePaused to false.
     * - pauseGame(): Pauses the game by setting isGamePaused to true.
     * - resumeGame(): Resumes the game by setting isGamePaused to false.
     * - endGame(): Ends the game by setting isGameRunning to false.
     * - shufflePlayers(): Randomly shuffles the order of players in the game.
     */







}
